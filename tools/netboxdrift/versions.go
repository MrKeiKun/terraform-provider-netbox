package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"github.com/Masterminds/semver/v3"

	"github.com/MrKeiKun/terraform-provider-netbox/internal/fwprovider"
)

// versionFile is the schema of one NetBox version.
type versionFile struct {
	Version string // for example 4.5.0, the oldest version the schema stands for
	Path    string
}

// parseVersions reads a list like 4.4.0=schema-4.4.json,4.5.0=schema-4.5.json, oldest first.
func parseVersions(s string) ([]versionFile, error) {
	var out []versionFile
	for _, part := range strings.Split(s, ",") {
		v, p, ok := strings.Cut(strings.TrimSpace(part), "=")
		if !ok || v == "" || p == "" {
			return nil, fmt.Errorf("-versions wants version=file pairs, got %q", part)
		}
		if _, err := semver.NewVersion(v); err != nil {
			return nil, fmt.Errorf("version %q: %w", v, err)
		}
		out = append(out, versionFile{v, p})
	}
	sort.Slice(out, func(i, j int) bool {
		a, _ := semver.NewVersion(out[i].Version)
		b, _ := semver.NewVersion(out[j].Version)
		return a.LessThan(b)
	})
	return out, nil
}

type since struct {
	resource string
	attrs    map[string]string
}

// writeVersions finds the first NetBox version that has each resource and each attribute of it, and
// writes the table to the file. What the oldest version has is not listed.
func writeVersions(files []versionFile, out string) error {
	eps := make([]map[string]*endpoint, len(files))
	for i, f := range files {
		data, err := os.ReadFile(f.Path)
		if err != nil {
			return err
		}
		list, err := parseEndpoints(data)
		if err != nil {
			return fmt.Errorf("%s: %w", f.Path, err)
		}
		eps[i] = map[string]*endpoint{}
		for _, ep := range list {
			eps[i][ep.Path] = ep
		}
	}

	resources, _ := fwprovider.Inventory()
	table := map[string]*since{}
	for _, s := range resources {
		// the first version that has the object type
		first := -1
		for i := range files {
			if ep := eps[i][s.Path]; ep != nil && ep.CanCreate {
				first = i
				break
			}
		}
		if first < 0 {
			continue
		}
		entry := &since{attrs: map[string]string{}}
		if first > 0 {
			entry.resource = files[first].Version
		} else {
			covered := map[string]bool{}
			for _, a := range s.Attrs {
				if a.Local || (!a.Optional && !a.Required) {
					continue
				}
				field := a.Name
				if a.Key != "" {
					field = a.Key
				}
				if len(a.Path) > 0 {
					field = a.Path[0]
				}
				if covered[field] {
					continue
				}
				covered[field] = true
				// the version where the field appears and from which it stays
				start, seen := -1, false
				for i := len(files) - 1; i >= 0; i-- {
					ep := eps[i][s.Path]
					if ep != nil && ep.Fields[field] {
						start, seen = i, true
						continue
					}
					break
				}
				if seen && start > 0 {
					entry.attrs[a.Name] = files[start].Version
				}
				if eps[0][s.Path] != nil && eps[0][s.Path].Fields[field] && !eps[len(files)-1][s.Path].Fields[field] {
					fmt.Fprintf(os.Stderr, "removed in a later version: %s.%s (%s)\n", s.TypeName, a.Name, field)
				}
			}
		}
		if entry.resource != "" || len(entry.attrs) > 0 {
			table[s.TypeName] = entry
		}
	}

	// the data sources, and the filters of the ones that list objects
	_, dataSources := fwprovider.Inventory()
	dsTable := map[string]*since{}
	for _, d := range dataSources {
		if d.Path == "" {
			continue
		}
		first := -1
		for i := range files {
			if eps[i][d.Path] != nil {
				first = i
				break
			}
		}
		if first < 0 {
			continue
		}
		entry := &since{attrs: map[string]string{}}
		if first > 0 {
			entry.resource = files[first].Version
		} else if d.Plural != nil {
			for name, param := range d.Plural.Filters {
				param = strings.TrimSuffix(param, "[]")
				start, seen := -1, false
				for i := len(files) - 1; i >= 0; i-- {
					if eps[i][d.Path] != nil && eps[i][d.Path].Query[param] {
						start, seen = i, true
						continue
					}
					break
				}
				if seen && start > 0 {
					entry.attrs[name] = files[start].Version
				}
			}
		}
		if entry.resource != "" || len(entry.attrs) > 0 {
			dsTable[d.TypeName] = entry
		}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by tools/netboxdrift from the NetBox API schemas. DO NOT EDIT.\n\n")
	b.WriteString("package fwprovider\n\nimport (\n\t\"strings\"\n\n\t\"github.com/MrKeiKun/terraform-provider-netbox/internal/fwresource\"\n)\n\n")
	b.WriteString("// versionSince lists the first NetBox version that has each resource and each attribute, for the ones\n")
	b.WriteString("// that the oldest tested version does not have.\n")
	b.WriteString("var versionSince = map[string]struct {\n\tResource string\n\tAttrs    map[string]string\n}{\n")
	var names []string
	for n := range table {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		e := table[n]
		fmt.Fprintf(&b, "\t%q: {Resource: %q, Attrs: map[string]string{", n, e.resource)
		var attrs []string
		for a := range e.attrs {
			attrs = append(attrs, a)
		}
		sort.Strings(attrs)
		for i, a := range attrs {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q: %q", a, e.attrs[a])
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("// dataSourceSince lists the first NetBox version that has each data source, and that has each filter\n")
	b.WriteString("// of the data sources that list objects, for the ones that the oldest tested version does not have.\n")
	b.WriteString("var dataSourceSince = map[string]struct {\n\tDataSource string\n\tFilters    map[string]string\n}{\n")
	var dsNames []string
	for n := range dsTable {
		dsNames = append(dsNames, n)
	}
	sort.Strings(dsNames)
	for _, n := range dsNames {
		e := dsTable[n]
		fmt.Fprintf(&b, "\t%q: {DataSource: %q, Filters: map[string]string{", n, e.resource)
		var filters []string
		for f := range e.attrs {
			filters = append(filters, f)
		}
		sort.Strings(filters)
		for i, f := range filters {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q: %q", f, e.attrs[f])
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n\n")
	b.WriteString(versionInit)
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	fmt.Printf("%d resources have a version table, written to %s\n", len(table), out)
	return os.WriteFile(out, src, 0o644)
}

const versionInit = `func init() {
	for _, list := range [][]*fwresource.Spec{standardResources, manualResources} {
		for _, spec := range list {
			since, ok := versionSince[spec.TypeName]
			if !ok {
				continue
			}
			spec.SinceVersion = since.Resource
			if len(since.Attrs) == 0 {
				continue
			}
			spec.Since = since.Attrs
			for i := range spec.Attrs {
				if v, ok := since.Attrs[spec.Attrs[i].Name]; ok && !strings.Contains(spec.Attrs[i].Description, "Needs NetBox") {
					spec.Attrs[i].Description += " Needs NetBox " + v + " or later."
				}
			}
		}
	}
}

func init() {
	for _, list := range [][]*fwresource.DataSourceSpec{HandwrittenDataSources(), generatedDataSources} {
		for _, spec := range list {
			since, ok := dataSourceSince[spec.TypeName]
			if !ok {
				continue
			}
			spec.SinceVersion = since.DataSource
			spec.FilterSince = since.Filters
			if since.DataSource != "" && !strings.Contains(spec.Description, "Needs NetBox") {
				spec.Description += " Needs NetBox " + since.DataSource + " or later."
			}
		}
	}
}
`
