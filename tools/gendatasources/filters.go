// ignoredFilters are list parameters that are not added to the data sources that are written by hand.
var ignoredFilters = map[string]bool{
	"created": true, "last_updated": true, "created_by_request": true, "updated_by_request": true, "modified_by_request": true,
}

// handwrittenFilters returns the names and parameters a hand written plural data source declares itself,
// without the ones that an earlier run added.
func handwrittenFilters(d *fwresource.DataSourceSpec) map[string]bool {
	added := fwprovider.GeneratedFilters()[d.TypeName]
	out := map[string]bool{}
	for _, list := range [][]fwresource.Attr{d.Attrs, d.ExtraFilters, d.FilterBlock} {
		for _, a := range list {
			if a.Computed && !a.Optional {
				continue
			}
			out[a.Name] = true
			if a.Key != "" {
				out[a.Key] = true
			}
			if a.Query != "" {
				out[strings.TrimSuffix(a.Query, "[]")] = true
			}
		}
	}
	for name, q := range d.Plural.Filters {
		if _, ok := added[name]; ok {
			continue
		}
		out[name] = true
		out[strings.TrimSuffix(q, "[]")] = true
	}
	return out
}

// missingFilters returns the filters of the list endpoint that the data source does not have.
func missingFilters(d *fwresource.DataSourceSpec, params map[string]bool) map[string]string {
	covered := handwrittenFilters(d)
	out := map[string]string{}
	for q, isList := range params {
		if ignoredQuery[q] || ignoredFilters[q] || strings.Contains(q, "__") || strings.HasPrefix(q, "cf_") || !validName.MatchString(q) {
			continue
		}
		if covered[q] || covered[strings.TrimSuffix(q, "_id")] || covered[q+"_id"] {
			continue
		}
		param := q
		if isList {
			param += "[]"
		}
		out[q] = param
	}
	return out
}

func filtersSource(extra map[string]map[string]string) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/gendatasources from the NetBox API schema. DO NOT EDIT.\n\n")
	b.WriteString("package fwprovider\n\n")
	b.WriteString("// generatedFilters are the filters of the list endpoint that the plural data sources written by hand\n")
	b.WriteString("// do not declare. They are added to those data sources when the provider starts.\n")
	b.WriteString("var generatedFilters = map[string]map[string]string{\n")
	var types []string
	for t := range extra {
		types = append(types, t)
	}
	sort.Strings(types)
	for _, t := range types {
		if len(extra[t]) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\t%q: {\n", t)
		var names []string
		for n := range extra[t] {
			names = append(names, n)
		}
		sort.Strings(names)
		for _, n := range names {
			fmt.Fprintf(&b, "\t\t%q: %q,\n", n, extra[t][n])
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")
	b.WriteString(initSource)
	return b.Bytes()
}

const initSource = `func init() {
	for _, spec := range HandwrittenDataSources() {
		if spec.Plural == nil || spec.Plural.NoFilter {
			continue
		}
		if spec.Plural.Filters == nil && len(generatedFilters[spec.TypeName]) > 0 {
			spec.Plural.Filters = map[string]string{}
		}
		for name, param := range generatedFilters[spec.TypeName] {
			if _, ok := spec.Plural.Filters[name]; !ok {
				spec.Plural.Filters[name] = param
			}
		}
	}
}
`
