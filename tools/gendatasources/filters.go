// ignoredFilters are list parameters that are not added to the data sources that are written by hand.
var ignoredFilters = map[string]bool{
	"created": true, "last_updated": true, "created_by_request": true, "updated_by_request": true, "modified_by_request": true,
}

// handwrittenFilters returns the names and parameters a hand written plural data source declares itself,
// without the ones that an earlier run added.
func handwrittenFilters(d *fwresource.DataSourceSpec) map[string]bool {
	added := fwprovider.GeneratedFilters()[d.TypeName]
	out := map[string]bool{}
	for _, list := range [][]fwresource.Attr{d.Attrs, d.ExtraFilters, d.FilterBlock} {
		for _, a := range list {
			if a.Computed && !a.Optional {
				continue
			}
			out[a.Name] = true
			if a.Key != "" {
				out[a.Key] = true
			}
			if a.Query != "" {
				out[strings.TrimSuffix(a.Query, "[]")] = true
			}
		}
	}
	for name, q := range d.Plural.Filters {
		if _, ok := added[name]; ok {
			continue
		}
		out[name] = true
		out[strings.TrimSuffix(q, "[]")] = true
	}
	return out
}

// missingFilters returns the filters of the list endpoint that the data source does not have.
func missingFilters(d *fwresource.DataSourceSpec, params map[string]bool) map[string]string {
	covered := handwrittenFilters(d)
	out := map[string]string{}
	for q, isList := range params {
		if ignoredQuery[q] || ignoredFilters[q] || strings.Contains(q, "__") || strings.HasPrefix(q, "cf_") || !validName.MatchString(q) {
			continue
		}
		if covered[q] || covered[strings.TrimSuffix(q, "_id")] || covered[q+"_id"] {
			continue
		}
		param := q
		if isList {
			param += "[]"
		}
		out[q] = param
	}
	return out
}

func filtersSource(extra map[string]map[string]string) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/gendatasources from the NetBox API schema. DO NOT EDIT.\n\n")
	b.WriteString("package fwprovider\n\n")
	b.WriteString("// generatedFilters are the filters of the list endpoint that the plural data sources written by hand\n")
	b.WriteString("// do not declare. They are added to those data sources when the provider starts.\n")
	b.WriteString("var generatedFilters = map[string]map[string]string{\n")
	var types []string
	for t := range extra {
		types = append(types, t)
	}
	sort.Strings(types)
	for _, t := range types {
		if len(extra[t]) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\t%q: {\n", t)
		var names []string
		for n := range extra[t] {
			names = append(names, n)
		}
		sort.Strings(names)
		for _, n := range names {
			fmt.Fprintf(&b, "\t\t%q: %q,\n", n, extra[t][n])
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")
	b.WriteString(initSource)
	return b.Bytes()
}

const initSource = `func init() {
	for _, spec := range HandwrittenDataSources() {
		if spec.Plural == nil || spec.Plural.NoFilter {
			continue
		}
		if spec.Plural.Filters == nil && len(generatedFilters[spec.TypeName]) > 0 {
			spec.Plural.Filters = map[string]string{}
		}
		for name, param := range generatedFilters[spec.TypeName] {
			if _, ok := spec.Plural.Filters[name]; !ok {
				spec.Plural.Filters[name] = param
			}
		}
	}
}
`

// lookups returns the lookup expressions the list endpoint has for each filter: "name" -> ["ic",
// "isw", "n", ...] for the parameters name__ic, name__isw, name__n and so on.
func (c *collection) lookups() map[string][]string {
	out := map[string][]string{}
	for q := range c.params {
		base, lookup, ok := strings.Cut(q, "__")
		if !ok || strings.HasPrefix(q, "cf_") || !c.hasParam(base) || !validName.MatchString(base) || !validName.MatchString(lookup) {
			continue
		}
		out[base] = append(out[base], lookup)
	}
	for base := range out {
		sort.Strings(out[base])
	}
	return out
}

func (c *collection) hasParam(name string) bool {
	_, ok := c.params[name]
	return ok
}

// lookupsSource writes the lookup expressions of every collection. NetBox has only a handful of
// different sets of lookups, so each filter points at its set by number.
func lookupsSource(lookups map[string]map[string][]string) []byte {
	var sets []string
	index := map[string]int{}
	var paths []string
	for p, byFilter := range lookups {
		if len(byFilter) > 0 {
			paths = append(paths, p)
		}
		for _, l := range byFilter {
			index[strings.Join(l, ",")] = 0
		}
	}
	for set := range index {
		sets = append(sets, set)
	}
	sort.Strings(sets)
	for i, set := range sets {
		index[set] = i
	}
	sort.Strings(paths)

	var b bytes.Buffer
	b.WriteString("\n// generatedLookupSets are the sets of lookup expressions NetBox has for a filter, for example\n")
	b.WriteString("// name__ic and name__isw for the filter name.\n")
	b.WriteString("var generatedLookupSets = [][]string{\n")
	for _, set := range sets {
		b.WriteString("\t{")
		for i, l := range strings.Split(set, ",") {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", l)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("// generatedLookups tells, by API path and query parameter, which lookup expressions the list\n")
	b.WriteString("// endpoint has for the parameter, as a number of generatedLookupSets. NetBox ignores a query\n")
	b.WriteString("// parameter it does not know and returns all objects, so the provider only sends lookups from\n")
	b.WriteString("// this table.\n")
	b.WriteString("var generatedLookups = map[string]map[string]uint8{\n")
	for _, p := range paths {
		fmt.Fprintf(&b, "\t%q: {", p)
		var names []string
		for n := range lookups[p] {
			names = append(names, n)
		}
		sort.Strings(names)
		for i, n := range names {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q: %d", n, index[strings.Join(lookups[p][n], ",")])
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return b.Bytes()
}
