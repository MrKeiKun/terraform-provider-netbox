// extraAttrs returns the fields of the object that the attributes of a data source written by hand do
// not cover yet, so that the data source returns the whole object.
func (c *collection) extraAttrs(doc obj, d *fwresource.DataSourceSpec, added map[string]bool) []attr {
	noun := d.Noun
	plural := d.Plural != nil
	if plural {
		noun = d.Plural.What
	}
	if noun == "" {
		noun = human(c.singular)
	}
	covered := map[string]bool{}
	mark := func(attrs []fwresource.Attr, skipAdded bool) {
		for _, a := range attrs {
			if skipAdded && added[a.Name] {
				continue
			}
			covered[a.Name] = true
			if a.Key != "" {
				covered[a.Key] = true
			}
			if len(a.Path) > 0 {
				covered[a.Path[0]] = true
			}
		}
	}
	mark(d.Attrs, true)
	mark(d.ExtraFilters, false)
	mark(d.FilterBlock, false)
	if d.CustomFields {
		covered["custom_fields"] = true
	}
	var out []attr
	for _, a := range c.attrs(doc, noun, plural) {
		if covered[a.name] || (a.key != "" && covered[a.key]) {
			continue
		}
		out = append(out, a)
	}
	return out
}

// extrasSource writes the attributes of the hand written data sources.
func extrasSource(extras map[string][]attr) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/gendatasources from the NetBox API schema. DO NOT EDIT.\n\n")
	b.WriteString("package fwprovider\n\nimport \"github.com/MrKeiKun/terraform-provider-netbox/internal/fwresource\"\n\n")
	b.WriteString("// dataSourceExtraAttrs are the fields of the NetBox objects that the attributes of the data sources\n// written by hand do not cover, by type name.\n")
	b.WriteString("var dataSourceExtraAttrs = map[string][]fwresource.Attr{\n")
	var names []string
	for n := range extras {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		if len(extras[n]) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\t%q: {\n", n)
		for _, a := range extras[n] {
			b.WriteString("\t\t" + a.String() + ",\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// addedNames returns the names of the attributes this tool added to a data source before.
func addedNames(typeName string) map[string]bool {
	out := map[string]bool{}
	for _, a := range fwprovider.ExtraDataSourceAttrs()[typeName] {
		out[a.Name] = true
	}
	return out
}

// resourceExtraAttrs returns the read-only fields of the object that a resource has no attribute for.
// They are computed attributes, such as when the object was created and how many objects refer to it.
// noExtraAttrs are resources that get no read-only attributes. Their port mappings are planned with
// values that differ from the state, which makes Terraform plan an update for every computed attribute
// that is not a plain pass-through.
var noExtraAttrs = map[string]bool{
	"netbox_device_front_port": true, "netbox_device_rear_port": true,
	"netbox_front_port_template": true, "netbox_rear_port_template": true,
}

func (c *collection) resourceExtraAttrs(doc obj, s *fwresource.Spec, added map[string]bool) []attr {
	if noExtraAttrs[s.TypeName] {
		return nil
	}
	noun := strings.TrimPrefix(s.TypeName, "netbox_")
	noun = human(noun)
	covered := map[string]bool{"tags": s.Tags, "custom_fields": s.CustomFields}
	for _, a := range s.Attrs {
		if added[a.Name] {
			continue
		}
		covered[a.Name] = true
		if a.Key != "" {
			covered[a.Key] = true
		}
		if len(a.Path) > 0 {
			covered[a.Path[0]] = true
		}
	}
	for _, sc := range s.Scopes {
		covered[sc.TypeKey] = true
		covered[sc.IDKey] = true
	}
	props, _ := c.item["properties"].(obj)
	var out []attr
	for _, a := range c.attrs(doc, noun, false) {
		raw := resolveProp(doc, props, a.name, a.key)
		if raw == nil || covered[a.name] || (a.key != "" && covered[a.key]) {
			continue
		}
		if ro, _ := raw["readOnly"].(bool); !ro && a.name != "created" && a.name != "last_updated" {
			continue
		}
		switch a.kind {
		case "String", "Int", "Float", "Bool", "JSON":
		default:
			continue
		}
		a.zero = false
		a.computed = true
		out = append(out, a)
	}
	return out
}

// resolveProp returns the schema of the property an attribute is made from, with its own readOnly flag.
func resolveProp(doc obj, props obj, name, key string) obj {
	field := name
	if key != "" {
		field = key
	}
	raw, _ := props[field].(obj)
	if raw == nil {
		return nil
	}
	out := obj{}
	for k, v := range resolve(doc, raw) {
		out[k] = v
	}
	if ro, ok := raw["readOnly"]; ok {
		out["readOnly"] = ro
	}
	return out
}

