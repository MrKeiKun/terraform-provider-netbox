package main

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"

	"github.com/MrKeiKun/terraform-provider-netbox/internal/fwprovider"
	"github.com/MrKeiKun/terraform-provider-netbox/internal/fwresource"
)

// extraAttrs returns the fields of the object that the attributes of a data source written by hand do
// not cover yet, so that the data source returns the whole object.
func (c *collection) extraAttrs(doc obj, d *fwresource.DataSourceSpec, added map[string]bool) []attr {
	noun := d.Noun
	plural := d.Plural != nil
	if plural {
		noun = d.Plural.What
	}
	if noun == "" {
		noun = human(c.singular)
	}
	covered := map[string]bool{}
	mark := func(attrs []fwresource.Attr, skipAdded bool) {
		for _, a := range attrs {
			if skipAdded && added[a.Name] {
				continue
			}
			covered[a.Name] = true
			if a.Key != "" {
				covered[a.Key] = true
			}
			if len(a.Path) > 0 {
				covered[a.Path[0]] = true
			}
		}
	}
	mark(d.Attrs, true)
	mark(d.ExtraFilters, false)
	mark(d.FilterBlock, false)
	if d.CustomFields {
		covered["custom_fields"] = true
	}
	var out []attr
	for _, a := range c.attrs(doc, noun, plural) {
		if covered[a.name] || (a.key != "" && covered[a.key]) {
			continue
		}
		out = append(out, a)
	}
	return out
}

// extrasSource writes the attributes of the hand written data sources.
func extrasSource(extras map[string][]attr) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/gendatasources from the NetBox API schema. DO NOT EDIT.\n\n")
	b.WriteString("package fwprovider\n\nimport \"github.com/MrKeiKun/terraform-provider-netbox/internal/fwresource\"\n\n")
	b.WriteString("// dataSourceExtraAttrs are the fields of the NetBox objects that the attributes of the data sources\n// written by hand do not cover, by type name.\n")
	b.WriteString("var dataSourceExtraAttrs = map[string][]fwresource.Attr{\n")
	var names []string
	for n := range extras {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		if len(extras[n]) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\t%q: {\n", n)
		for _, a := range extras[n] {
			b.WriteString("\t\t" + a.String() + ",\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// addedNames returns the names of the attributes this tool added to a data source before.
func addedNames(typeName string) map[string]bool {
	out := map[string]bool{}
	for _, a := range fwprovider.ExtraDataSourceAttrs()[typeName] {
		out[a.Name] = true
	}
	return out
}
